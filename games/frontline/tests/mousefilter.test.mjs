// 마우스 이상치 필터 (서버·브라우저 없이, 1초 미만): 정상 플릭은 그대로, 고립된 스파이크·락 직후 이벤트만 버린다
import { check, failed } from './helpers.mjs';
import { createMouseFilter, LOCK_SKIP } from '../client/js/mousefilter.js';

const run = (events, { lock = false } = {}) => {
  const f = createMouseFilter(); if (lock) f.onLock();
  let t = 1000; const out = [];
  for (const [dx, gap = 8] of events) { t += gap; out.push(f.apply(dx, 0, t)); }
  return out;
};

// 1) 정상 플릭: 0 → 점점 커져 130px 까지, 다시 줄어든다 (8ms 간격). 하나도 버리지 않고 값도 그대로
const flick = [3, 8, 20, 45, 80, 120, 150, 170, 175, 160, 120, 70, 30, 10];
let r = run(flick.map(v => [v]));
check(r.every(x => !x[2]) && r.every((x, i) => x[0] === flick[i]), '빠른 플릭(점점 커지는 연속 이벤트)은 하나도 버리지 않고 값도 그대로');

// 2) 1000Hz 마우스의 빠른 180° 회전 (1ms 간격 · 이벤트당 10~20px)
const hi = Array.from({ length: 200 }, (_, i) => [12 + 6 * Math.sin(i / 10), 1]);
r = run(hi);
check(r.every(x => !x[2]), '고폴링(1ms 간격) 연속 회전도 그대로');

// 3) 가만히 있다가 첫 이벤트가 160 미만이면 (플릭의 시작) 통과
r = run([[2], [1], [0], [150]]);
check(!r[3][2] && r[3][0] === 150, '정지 상태에서 시작한 큰 플릭의 첫 이벤트(150px)는 통과 (절대 기준 미만)');

// 4) 고립된 스파이크: 평범한 움직임(5~15px) 중에 한 번 400px
r = run([[8], [10], [6], [12], [400], [9], [7]]);
check(r[4][2] && r[4][0] === 0, '평범한 움직임 중 고립된 400px 스파이크는 버린다');
check(!r[5][2] && r[5][0] === 9 && !r[6][2], '스파이크 다음 이벤트는 정상 처리 (이어지는 입력 영향 없음)');

// 5) 반대 방향 스파이크
r = run([[-5], [-7], [-6], [-600], [-8]]);
check(r[3][2], '음수 방향 스파이크도 버린다');

// 6) 프레임 정지 뒤 몰린 합산 값: 간격이 길면(150ms) 큰 값도 통과 (사람이 실제로 움직인 양)
r = run([[10], [12], [9], [420, 150], [11]]);
check(!r[3][2] && r[3][0] === 420, '프레임 정지(150ms) 뒤 합쳐진 420px 은 실제 움직임이라 통과');

// 7) 사람 손이 아닌 값은 합산이어도 자른다
r = run([[10], [12], [9], [9000, 150]]);
check(!r[3][2] && r[3][0] === 1500, '9000px 은 1500 으로 자른다');

// 8) 포인터 락 직후 첫 이벤트는 버린다
r = run([[500], [-300], [8], [9]], { lock: true });
check(r[0][2] && r[1][2] && !r[2][2] && LOCK_SKIP === 2, `포인터 락 직후 ${LOCK_SKIP}개는 버리고 그 다음부터 통과`);

// 9) 연속으로 큰 스파이크가 반복돼도(2번) 평균을 오염시키지 않아 둘 다 버린다
r = run([[8], [10], [9], [400], [380], [10]]);
check(r[3][2] && r[4][2] && !r[5][2], '연속 스파이크 2개도 모두 버린다');

process.exit(failed() ? 1 : 0);
